// Produces SQL Editor-ready files locally. Never connects to a database.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const directory = path.join(root, 'migrations');
const files = fs.readdirSync(directory).filter(f => /^\d{14}_.+\.sql$/.test(f)).sort();
const migrations = files.map(name => ({ name, sql: fs.readFileSync(path.join(directory, name), 'utf8') }));
const source = migrations.map(m => m.sql).join('\n');
const collect = pattern => [...new Set([...source.matchAll(pattern)].map(m => m[1]))].sort();
const tables = collect(/CREATE TABLE\s+(?:IF NOT EXISTS\s+)?(?:public\.)?(\w+)/gi);
const views = collect(/CREATE (?:OR REPLACE )?VIEW\s+(?:public\.)?(\w+)/gi);
const functions = collect(/CREATE (?:OR REPLACE )?FUNCTION\s+(?:public\.)?(\w+)\s*\(\s*\)/gi);
const types = collect(/CREATE TYPE\s+(?:public\.)?(\w+)\s+AS ENUM/gi);
const list = values => values.map(v => "'" + v + "'").join(',');
const out = path.join(root, 'generated');
fs.mkdirSync(out, { recursive: true });

const reset = `-- DESTRUCTIVE: deletes MarginFlow app tables and their data only.
-- Managed auth/storage schemas, buckets, identities and unrelated extensions stay intact.
-- Stop writes and take a backup first. Run separately from 02_create.sql.
BEGIN;
DO $$
DECLARE confirmation text := 'CHANGE_ME'; t text; unexpected text;
BEGIN
  IF confirmation IS DISTINCT FROM 'DELETE MARGINFLOW TEST DATA' THEN
    RAISE EXCEPTION 'Reset is locked. Replace CHANGE_ME only after confirming this is disposable test data.';
  END IF;
  SELECT string_agg(c.relname, ', ') INTO unexpected
  FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
  WHERE n.nspname='public' AND c.relkind IN ('r','p','v','m','f')
    AND c.relname <> ALL(ARRAY[${list([...tables, ...views, 'marginflow_schema_migrations'])}]);
  IF unexpected IS NOT NULL THEN
    RAISE EXCEPTION 'Unrecognized public objects: %. Review dependencies before resetting.',unexpected;
  END IF;
  FOREACH t IN ARRAY ARRAY[${list(views)}] LOOP
    EXECUTE format('DROP VIEW IF EXISTS public.%I CASCADE',t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY[${list([...tables, 'marginflow_schema_migrations'])}] LOOP
    EXECUTE format('DROP TABLE IF EXISTS public.%I CASCADE',t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY[${list(functions)}] LOOP
    EXECUTE format('DROP FUNCTION IF EXISTS public.%I() CASCADE',t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY[${list(types)}] LOOP
    EXECUTE format('DROP TYPE IF EXISTS public.%I CASCADE',t);
  END LOOP;
END $$;
COMMIT;
`;

const preflight = `-- GENERATED by node production-supabase/prepare.mjs. Review before running.
-- Run ONLY on an empty app schema, or AFTER the separate, reviewed test reset.
-- No demo data. This is not an upgrade script for a populated database.
DO $$ BEGIN
  IF to_regclass('auth.users') IS NULL OR to_regclass('storage.buckets') IS NULL THEN
    RAISE EXCEPTION 'This package requires a Supabase project (Auth and Storage schemas).';
  END IF;
  IF EXISTS(SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relname=ANY(ARRAY[${list([...tables, 'marginflow_schema_migrations'])}]))
    OR to_regtype('public.marketplace_enum') IS NOT NULL THEN
    RAISE EXCEPTION 'Existing MarginFlow objects found. Stop: use a reviewed reset or data-preserving migration.';
  END IF;
END $$;
SET search_path=public,extensions;
`;
const metadata = `
-- App package receipt, separate from Supabase CLI migration history.
BEGIN;
CREATE TABLE public.marginflow_schema_migrations(version text PRIMARY KEY, checksum text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now());
ALTER TABLE public.marginflow_schema_migrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.marginflow_schema_migrations FROM PUBLIC,anon,authenticated;
INSERT INTO public.marginflow_schema_migrations(version,checksum) VALUES
${migrations.map(m => `('${m.name.slice(0,14)}','${crypto.createHash('sha256').update(m.sql).digest('hex')}')`).join(',\n')};
COMMIT;
`;
fs.writeFileSync(path.join(out, '01_reset_test.sql'), reset);
const resources = ['20_runtime_role.sql', '30_profile_avatars.sql'].map(name =>
  `\n-- SOURCE: operations/${name}\n${fs.readFileSync(path.join(root, 'operations', name), 'utf8')}\n`).join('');
fs.writeFileSync(path.join(out, '02_create.sql'), preflight + migrations.map(m => `\n-- SOURCE: ${m.name}\n${m.sql}\n`).join('') + resources + metadata);
console.log(`Prepared ${migrations.length} migrations, ${tables.length} tables: generated/01_reset_test.sql and generated/02_create.sql`);
